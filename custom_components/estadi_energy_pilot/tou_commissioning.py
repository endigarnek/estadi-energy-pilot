"""Deye TOU commissioning preflight: read-only evidence, never executable writes.

The six TOU time rows are time *boundaries*, not six independently controlled
windows. A plan like 01:30–04:45 is NOT the same as the device's 01:00–05:00
period. Never silently convert a tariff plan into inverter configuration.
"""
from __future__ import annotations

from datetime import datetime
from math import isfinite
from typing import Any

from .deye_tou import SLOT_COUNT, SLOT_FIELDS, snapshot_config


REQUIRED_GLOBALS = (
    "select.deye_time_of_use",
    "switch.deye_battery_grid_charging",
)
PROTECTED_CONTROLS = (
    "number.deye_battery_grid_charging_current",
    "number.deye_battery_max_charging_current",
    "number.deye_grid_max_import_power",
)
FIRMWARE_SEMANTICS_CONFIRMED = False


def _time_label(value: Any) -> str | None:
    if not isinstance(value, str):
        return None
    try:
        dt = datetime.fromisoformat(value)
    except ValueError:
        return None
    return dt.strftime("%H:%M") if dt.tzinfo is not None else None


def audit_tou_map(inventory: dict, *, plan: dict | None = None,
                  get_state=None) -> dict:
    """Inventory all observed slots and identify what *blocks* a write test.

    No service calls, register addresses, command values or automatic action
    sequence are generated by this function.
    """
    raw_slots = inventory.get("programy") or []
    globals_found = inventory.get("stan_globalny") or {}
    complete = inventory.get("status") == "odczytano_6_programow"
    program_rows = []
    missing = []
    unknown = []
    time_boundaries = []
    for slot in range(1, SLOT_COUNT + 1):
        source = next((x for x in raw_slots if x.get("slot") == slot), {})
        row = {"program": slot}
        for field in SLOT_FIELDS:
            item = source.get(field) or {}
            eid = item.get("encja")
            status = item.get("status")
            value = item.get("wartosc")
            row[field] = {"entity": eid if isinstance(eid, str) else None,
                          "value": value, "read_status": status}
            if status != "ok":
                missing.append(f"Program {slot}: {field}")
            if status == "ok" and not isinstance(eid, str):
                unknown.append(f"Program {slot}: {field} nie ma jednoznacznej encji")
        if row["time"]["read_status"] == "ok":
            time_boundaries.append(row["time"]["value"])
        program_rows.append(row)

    controls = []
    for key in REQUIRED_GLOBALS + PROTECTED_CONTROLS:
        state = get_state(key) if get_state is not None else None
        val = str(getattr(state, "state", "unknown")) if state else globals_found.get(key)
        controls.append({"entity": key, "value": val, "source_read_only": True})
        if val is None or val in ("unknown", "unavailable"):
            unknown.append("Nie odczytano globalnego ustawienia " + key)

    global_grid = inventory.get("global_grid_charge")
    modes = inventory.get("charging_modes_by_program") or {}
    active_grid = [n for n in range(1, 7) if modes.get(n) in ("Grid", "Both")]
    time_unique = len(time_boundaries) == 6 and len(set(time_boundaries)) == 6
    chronological = (time_unique and time_boundaries == sorted(time_boundaries))

    blockers = []
    if not complete or missing:
        blockers.append("Niekompletna lub niejednoznaczna mapa 24 pól TOU")
    if not time_unique or not chronological:
        blockers.append("Niepotwierdzona kolejność i unikalność granic TOU")
    if global_grid != "on":
        blockers.append("Globalne zezwolenie Grid Charge nie jest włączone")
    if not active_grid:
        blockers.append("Żaden program TOU nie ma trybu ładowania Grid/Both")
    if inventory.get("tou_mode_raw") in (None, "Disabled", "unknown", "unavailable"):
        blockers.append("Wyłączony lub nieznany tryb wyboru dni TOU")
    else:
        blockers.append("Niezweryfikowane znaczenie wyboru dni TOU dla firmware")
    blockers.extend([
        "Brak potwierdzonej możliwości fizycznego zapisu i odczytu zwrotnego Deye",
        "Niepotwierdzony maksymalny prąd dopuszczony przez BMS i tor DC",
        "Niepotwierdzone limity trzech faz, 15 kW przyłącza i margines bezpieczeństwa",
        "Brak zatwierdzonej procedury wycofania zmian po awarii komunikacji",
    ])
    if unknown:
        blockers.extend(unknown[:8])

    model_start = _time_label((plan or {}).get("start"))
    model_end = _time_label((plan or {}).get("end_window"))
    window_alignment = {
        "plan_start_local": model_start, "plan_end_local": model_end,
        "tou_boundaries_local": time_boundaries,
        "start_aligned": model_start in time_boundaries if model_start else None,
        "end_aligned": model_end in time_boundaries if model_end else None,
        "verified_schedule_for_tariff": False,
    }
    if model_start and model_end and time_unique:
        if model_start not in time_boundaries or model_end not in time_boundaries:
            blockers.append(
                "Okno proponowanego ładowania nie pokrywa się dokładnie "
                "z obecnymi granicami programów TOU"
            )
    snapshot = snapshot_config(inventory)
    return {
        "readback_status": "ok" if complete and not missing else "niekompletne",
        "readback_fields": inventory.get("odczytane_pola"),
        "readback_required": SLOT_COUNT * len(SLOT_FIELDS),
        "operational_status": "blokada",
        "can_write": False,
        "commands_sent": 0,
        "write_actions": [],
        "safe_rollback_proven": False,
        "snapshot_in_memory": snapshot is not None,
        "snapshot_persisted": False,
        "global_grid_charge": global_grid,
        "time_of_use_mode": inventory.get("tou_mode_raw"),
        "active_grid_programs": active_grid,
        "program_rows": program_rows,
        "protected_setpoints": controls,
        "time_order_valid": bool(chronological),
        "window_alignment": window_alignment,
        "blockers": blockers,
        "model_firmware_verified": FIRMWARE_SEMANTICS_CONFIRMED,
    }
